function getCurrentLang() {
  try {
    return localStorage.getItem('madar_lang') === 'en' ? 'en' : 'ar';
  } catch (error) {
    return 'ar';
  }
}

function getTranslation(key, lang = getCurrentLang()) {
  return (lang === 'en' ? en : ar)[key] || key;
}

function getSavedContent() {
  try {
    return JSON.parse(localStorage.getItem('madar_content') || 'null') || {};
  } catch (error) {
    return {};
  }
}

function applyTranslations(lang) {
  const dictionary = lang === 'en' ? en : ar;
  const savedContent = getSavedContent();

  document.querySelectorAll('[data-i18n]').forEach(element => {
    const key = element.dataset.i18n;
    const contentKey = element.dataset.contentKey;
    if (contentKey && savedContent[contentKey] && savedContent[contentKey] !== ar[key]) return;
    if (dictionary[key]) element.textContent = dictionary[key];
  });

  document.querySelectorAll('[data-i18n-aria-label]').forEach(element => {
    const value = dictionary[element.dataset.i18nAriaLabel];
    if (value) element.setAttribute('aria-label', value);
  });
  document.querySelectorAll('[data-i18n-alt]').forEach(element => {
    const value = dictionary[element.dataset.i18nAlt];
    if (value) element.setAttribute('alt', value);
  });
  document.querySelectorAll('[data-i18n-title]').forEach(element => {
    const value = dictionary[element.dataset.i18nTitle];
    if (value) element.setAttribute('title', value);
  });

  document.querySelectorAll('[data-language-toggle]').forEach(button => {
    button.textContent = dictionary.language_button;
    button.setAttribute('aria-label', dictionary.switch_language);
  });
  document.querySelectorAll('[data-theme-toggle]').forEach(button => {
    button.setAttribute('aria-label', document.documentElement.dataset.theme === 'dark' ? dictionary.switch_theme_light : dictionary.switch_theme_dark);
    const icon = button.querySelector('i');
    if (icon) {
      icon.classList.toggle('fa-sun', document.documentElement.dataset.theme === 'dark');
      icon.classList.toggle('fa-moon', document.documentElement.dataset.theme !== 'dark');
    }
  });
}

function setLanguage(lang) {
  const selectedLang = lang === 'en' ? 'en' : 'ar';
  const root = document.documentElement;
  root.lang = selectedLang;
  root.dir = selectedLang === 'ar' ? 'rtl' : 'ltr';
  root.classList.toggle('ltr', selectedLang === 'en');
  root.style.setProperty('--site-font', selectedLang === 'en' ? "'Poppins', sans-serif" : "'Cairo', sans-serif");

  const bootstrap = document.getElementById('bootstrap-css');
  if (bootstrap) {
    bootstrap.href = selectedLang === 'ar'
      ? 'https://cdn.jsdelivr.net/npm/bootstrap@5.3.8/dist/css/bootstrap.rtl.min.css'
      : 'https://cdn.jsdelivr.net/npm/bootstrap@5.3.8/dist/css/bootstrap.min.css';
  }

  try {
    localStorage.setItem('madar_lang', selectedLang);
  } catch (error) {
    // Language switching still works when storage is unavailable.
  }
  applyTranslations(selectedLang);
}

function setTheme(theme) {
  const selectedTheme = theme === 'dark' ? 'dark' : 'light';
  document.documentElement.dataset.theme = selectedTheme;
  try {
    localStorage.setItem('madar_theme', selectedTheme);
  } catch (error) {
    // Theme switching still works when storage is unavailable.
  }
  applyTranslations(getCurrentLang());
}

function toggleTheme() {
  setTheme(document.documentElement.dataset.theme === 'dark' ? 'light' : 'dark');
}

window.ar = ar;
window.en = en;
window.applyTranslations = applyTranslations;
window.getCurrentLang = getCurrentLang;
window.getTranslation = getTranslation;
window.setLanguage = setLanguage;
window.setTheme = setTheme;
window.toggleTheme = toggleTheme;

document.addEventListener('DOMContentLoaded', () => {
  let savedTheme = 'light';
  try {
    savedTheme = localStorage.getItem('madar_theme') === 'dark' ? 'dark' : 'light';
  } catch (error) {
    savedTheme = 'light';
  }
  setTheme(savedTheme);
  setLanguage(getCurrentLang());
});
